/**
 * Thời gian hoạt động kinh tế (trừ mini-game):
 * - Ở lần thu hoạch đầu tiên (completedCount <= 0): mặc định hoàn thành trong 1 tiếng đồng hồ (3.600s).
 * - Các lần thu hoạch tiếp theo (completedCount = 1, 2, 3, ...): tăng theo cấp số nhân ×2 (2g, 4g) và kẹp trần tối đa 6 tiếng (21.600s).
 */
export function computeEconomicCycleSeconds(
  completedCount = 0,
  baseSec = FIRST_ECONOMIC_CYCLE_SEC
): number {
  const step = Math.max(0, Math.min(20, Math.floor(completedCount)));
  const startSec = baseSec > 0 ? baseSec : FIRST_ECONOMIC_CYCLE_SEC;
  const raw = Math.max(60, Math.round(startSec * Math.pow(2, step)));
  return Math.min(MAX_ECONOMIC_CYCLE_SEC, raw);
}

export function getBuildingEffectiveCycleSec(
  b: { harvestCycleCount?: number } | null | undefined,
  item: Pick<CatalogItem, 'cycleSec'> | null | undefined
): number {
  if (!item || item.cycleSec <= 0) return 0;
  return computeEconomicCycleSeconds(b?.harvestCycleCount ?? 0, item.cycleSec);
}

/**
 * Mức thời gian còn lại tối thiểu mà người chơi có thể rút ngắn công trình đang xây
 * thông qua thắng Minigame (Match-3 / 4 môn Giải Đố) hoặc trả lời đúng Quiz Ngoại Ngữ:
 * - Công trình có thời gian xây gốc >= 1 giờ (lên tới tối đa 3 ngày): sàn còn lại tối thiểu là 1 giờ (3.600s).
 * - Công trình trung cấp (15 phút .. < 60 phút): sàn còn lại tối thiểu là 10 phút (600s).
 * - Công trình cấp đầu (< 15 phút): sàn còn lại tối thiểu là 5 phút (300s).
 */
export function getMinRemainingBuildFloorSec(baseBuildSec: number): number {
  const sec = Math.max(0, Math.round(baseBuildSec));
  if (sec <= 0) return 0;
  if (sec >= MIN_LONG_BUILD_FLOOR_SECONDS) return MIN_LONG_BUILD_FLOOR_SECONDS;
  if (sec >= 900) return 600;
  return Math.min(sec, 300);
}

/**
 * Thời gian xây dựng thực tế (Real-Time Construction & Incubation):
 * - Thửa đất canh tác, đồng cỏ chăn thả, ô vườn hoa ghép rào, đường đi & địa hình đặt tức thì (0s) để kéo lướt liền mạch.
 * - Mỗi công trình kiến trúc, xưởng chế biến, cửa tiệm & khu bảo tồn có thời gian chờ riêng biệt,
 *   tăng dần theo cấp mở khóa tới tối đa 3 ngày (259.200s).
 */
export function computeCostScaledBuildSeconds(cost: number): number {
  if (cost <= 45) return 0;
  return Math.min(MAX_WAIT_DURATION_SECONDS, Math.max(360, Math.round(cost * 8.1)));
}

export function computeRealTimeBuildSeconds(
  item: Pick<
    CatalogItem,
    | 'id'
    | 'category'
    | 'cost'
    | 'buildDurationSec'
    | 'isCoasterTrackPiece'
    | 'isZooFence'
    | 'elevationDelta'
    | 'isFarmlandPlot'
    | 'isAnimalPasturePlot'
  >
): number {
  if (
    item.category === 'path' ||
    item.category === 'terrain' ||
    item.isCoasterTrackPiece ||
    item.isZooFence ||
    Boolean(item.elevationDelta) ||
    item.isFarmlandPlot ||
    item.isAnimalPasturePlot
  ) {
    return 0;
  }
  return Math.min(MAX_WAIT_DURATION_SECONDS, Math.max(0, Math.round(item.buildDurationSec ?? 0)));
}

export function formatDurationCompactVi(totalSec: number): string {
  const sec = Math.max(0, Math.ceil(totalSec));
  if (sec < 60) return `${sec}s`;
  if (sec >= 86400) {
    const days = Math.floor(sec / 86400);
    const remHours = Math.floor((sec % 86400) / 3600);
    const remMins = Math.floor((sec % 3600) / 60);
    if (remHours === 0 && remMins === 0) return `${days} ngày`;
    if (remMins === 0) return `${days}ng ${remHours}g`;
    return `${days}ng ${remHours}g ${remMins}p`;
  }
  const hours = Math.floor(sec / 3600);
  const mins = Math.floor((sec % 3600) / 60);
  const remSec = sec % 60;
  if (hours > 0) {
    return mins > 0 ? `${hours}g ${mins}p` : `${hours} giờ`;
  }
  return remSec > 0 ? `${mins}p ${remSec}s` : `${mins} phút`;
}

export function formatDurationCountdownVi(totalSec: number): string {
  const sec = Math.max(0, Math.ceil(totalSec));
  if (sec < 60) return `${sec}s`;
  if (sec >= 86400) {
    const days = Math.floor(sec / 86400);
    const remHours = Math.floor((sec % 86400) / 3600);
    const remMins = Math.floor((sec % 3600) / 60);
    return `${days}ng ${String(remHours).padStart(2, '0')}g ${String(remMins).padStart(2, '0')}p`;
  }
  const hours = Math.floor(sec / 3600);
  const mins = Math.floor((sec % 3600) / 60);
  const remSec = sec % 60;
  if (hours > 0) {
    return `${hours}g ${String(mins).padStart(2, '0')}p ${String(remSec).padStart(2, '0')}s`;
  }
  return `${mins}p ${String(remSec).padStart(2, '0')}s`;
}


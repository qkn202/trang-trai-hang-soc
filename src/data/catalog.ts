const FARM_ICON_SRC_CACHE = new Map<FarmItemId, string>();

export function getFarmItemIconSrc(itemId: FarmItemId): string {
  const cached = FARM_ICON_SRC_CACHE.get(itemId);
  if (cached) return cached;
  const iconKey =
    itemId in FARM_CROPS
      ? FARM_CROPS[itemId as FarmCropId].iconKey
      : FARM_GOODS[itemId as FarmGoodId].iconKey;
  const src = `/sprites/${iconKey}.png`;
  FARM_ICON_SRC_CACHE.set(itemId, src);
  return src;
}

export function getFarmItemMeta(itemId: FarmItemId): {
  id: FarmItemId;
  name: string;
  emoji: string;
  iconKey: string;
  iconSrc: string;
  sellValue: number;
  isCrop: boolean;
} {
  if (itemId in FARM_CROPS) {
    const c = FARM_CROPS[itemId as FarmCropId];
    return {
      id: c.id,
      name: c.name,
      emoji: c.emoji,
      iconKey: c.iconKey,
      iconSrc: getFarmItemIconSrc(c.id),
      sellValue: c.sellValue,
      isCrop: true,
    };
  }
  const g = FARM_GOODS[itemId as FarmGoodId];
  return {
    id: g.id,
    name: g.name,
    emoji: g.emoji,
    iconKey: g.iconKey,
    iconSrc: getFarmItemIconSrc(g.id),
    sellValue: g.sellValue,
    isCrop: false,
  };
}


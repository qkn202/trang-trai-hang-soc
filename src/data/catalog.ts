const FARM_ICON_SRC_CACHE = new Map<FarmItemId, string>();

export function getFarmItemIconSrc(itemId: FarmItemId): string {
  const cached = FARM_ICON_SRC_CACHE.get(itemId);
  if (cached) return cached;
  const cropMeta = Object.prototype.hasOwnProperty.call(FARM_CROPS, itemId)
    ? FARM_CROPS[itemId as FarmCropId]
    : undefined;
  const goodMeta = !cropMeta && Object.prototype.hasOwnProperty.call(FARM_GOODS, itemId)
    ? FARM_GOODS[itemId as FarmGoodId]
    : undefined;
  const iconKey = cropMeta?.iconKey ?? goodMeta?.iconKey ?? 'ui_icon_crop_ottery_wheat';
  const src = `/game/trang-trai-hang-soc/sprites/${iconKey}.webp`;
  if (cropMeta || goodMeta) {
    FARM_ICON_SRC_CACHE.set(itemId, src);
  }
  return src;
}

export function getFarmItemMeta(itemId: FarmItemId): {
  id: FarmItemId;
  name: string;
  emoji: string;
  iconKey: string;
  iconSrc: string;
  sellValue: number;
  isCrop: boolean;
} {
  if (Object.prototype.hasOwnProperty.call(FARM_CROPS, itemId)) {
    const c = FARM_CROPS[itemId as FarmCropId];
    return {
      id: c.id,
      name: c.name,
      emoji: c.emoji,
      iconKey: c.iconKey,
      iconSrc: getFarmItemIconSrc(c.id),
      sellValue: c.sellValue,
      isCrop: true,
    };
  }
  if (Object.prototype.hasOwnProperty.call(FARM_GOODS, itemId)) {
    const g = FARM_GOODS[itemId as FarmGoodId];
    return {
      id: g.id,
      name: g.name,
      emoji: g.emoji,
      iconKey: g.iconKey,
      iconSrc: getFarmItemIconSrc(g.id),
      sellValue: g.sellValue,
      isCrop: false,
    };
  }
  return {
    id: itemId,
    name: String(itemId),
    emoji: '📦',
    iconKey: 'ui_icon_crop_ottery_wheat',
    iconSrc: '/game/trang-trai-hang-soc/sprites/ui_icon_crop_ottery_wheat.webp',
    sellValue: 1,
    isCrop: false,
  };
}

function yuleDecor(
  id: string,
  name: string,
  yuleCollection: YuleCollectionId,
  width: number,
  height: number,
  unlockLevel: number,
  cost: number,
  description: string,
  loreTip: string,
  flags?: Pick<CatalogItem, 'isBench' | 'isPrivacyShield' | 'isInteractiveSpellSpot'>
): CatalogItem {
  const area = width * height;
  const wonder = Number(Math.min(9.9, 1.8 + cost / 95 + area * 0.45).toFixed(1));
  const comfort = Number(
    Math.min(8.5, (flags?.isBench ? 4.2 : 1.6) + cost / 180 + area * 0.25).toFixed(1)
  );
  return {
    id,
    name,
    category: 'decor',
    yuleCollection,
    description,
    loreTip,
    width,
    height,
    cost,
    unlockLevel,
    spriteKey: id,
    buildDurationSec: 0,
    baseIncome: 0,
    xpPerCollect: 0,
    cycleSec: 0,
    maxStorageCycles: 0,
    wonder,
    thrill: flags?.isInteractiveSpellSpot ? 0.8 : 0,
    comfort,
    ...flags,
  };
}


export function getZoneAt(gx: number, gy: number): ZoneDef {
  for (const z of ZONES) {
    if (gx >= z.x1 && gx <= z.x2 && gy >= z.y1 && gy <= z.y2) {
      return z;
    }
  }
  return ZONES[0];
}

export function getZoneById(id: ZoneId): ZoneDef {
  return ZONES.find((z) => z.id === id) || ZONES[0];
}
